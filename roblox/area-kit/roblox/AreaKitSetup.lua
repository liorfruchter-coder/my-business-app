--[[
	AreaKitSetup (generated by roblox_lua.py)
	Turns imported area-kit FBX models into ready-to-place Roblox models.

	1. Put this ModuleScript and AreaKitStyles side by side (e.g. in ServerStorage).
	2. Import an area's FBX with the 3D Importer (e.g. fbx/Beach.fbx), leave it in Workspace.
	3. In the command bar:
	       require(game.ServerStorage.AreaKitSetup).Run(workspace.Beach)
	   or for everything you imported at once:
	       require(game.ServerStorage.AreaKitSetup).Run(workspace)

	For every kit asset found under the instance you pass, it
	  * gathers the asset's MeshParts ("<Asset>_<Style>") into one Model named <Asset>
	  * paints each part from AreaKitStyles (Color, Material, Transparency) and drops imported SurfaceAppearances
	  * anchors everything; glowing parts and water don't collide or cast shadows; slivers don't collide
	  * scales the model to its designed size in studs (fixes any unit mix-up in the import)
	  * turns it a quarter turn if its footprint came in sideways
	  * sets its pivot to the bottom centre of its footprint (front faces -Z)
	  * gives each glowing part one PointLight (opts.Lights = false to skip)
	  * moves it to ReplicatedStorage.AreaKit.<Area>.<Asset>
	Options: Run(root, { Accent = Color3, Party = Color3, Lights = true, Destination = Instance, Keep = false })
	(Keep = true styles the models where they are instead of moving them.)
]]

