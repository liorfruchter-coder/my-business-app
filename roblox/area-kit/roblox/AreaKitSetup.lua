local LIGHT_RANGE = 24

local function parse(name)
	local asset, style = string.match(name, "^(%w+)_(%w+)")
	return asset, style
end

local function folderFor(dest, area)
	local f = dest:FindFirstChild(area)
	if not f then
		f = Instance.new("Folder")
		f.Name = area
		f.Parent = dest
	end
	return f
end

local function paint(part, styleName, opts)
	local s = Styles[styleName]
	for _, c in ipairs(part:GetChildren()) do
		if c:IsA("SurfaceAppearance") then
			c:Destroy()
		end
	end
	part.Anchored = true
	if not s then
		warn("AreaKitSetup: no style '" .. tostring(styleName) .. "' for " .. part:GetFullName())
		return
	end
	local color = s.Color
	if s.Tint and opts[styleName] then
		color = opts[styleName]
	end
	part.Color = color
	part.Material = s.Material
	part.Transparency = s.Transparency or 0
	part.CastShadow = not s.Glow and (s.Transparency or 0) < 0.3
	if s.Glow or styleName == "Water" then
		part.CanCollide = false
	end
	if part.Size.X < 0.6 or part.Size.Y < 0.6 or part.Size.Z < 0.6 then
		part.CanCollide = false
	end
	if s.Glow and opts.Lights ~= false and not part:FindFirstChildOfClass("PointLight") then
		local l = Instance.new("PointLight")
		l.Color = color
		l.Range = math.min(LIGHT_RANGE, math.max(8, part.Size.Magnitude))
		l.Brightness = 1.2
		l.Shadows = false
		l.Parent = part
	end
end

local function fit(model, info)
	model.WorldPivot = CFrame.new(model:GetBoundingBox().Position)
	local size = model:GetExtentsSize()
	local want = info.Size
	-- footprint came in sideways? (only telling when it isn't square)
	if math.abs(want.X - want.Z) > 0.2 * math.max(want.X, want.Z)
		and math.abs(size.X - want.Z) + math.abs(size.Z - want.X) < math.abs(size.X - want.X) + math.abs(size.Z - want.Z) then
		model:PivotTo(model:GetPivot() * CFrame.Angles(0, math.rad(90), 0))
		model.WorldPivot = CFrame.new(model:GetBoundingBox().Position)
		size = model:GetExtentsSize()
	end
	if size.Y > 0 then
		local k = want.Y / size.Y
		if math.abs(k - 1) > 0.02 then
			model:ScaleTo(model:GetScale() * k)
		end
	end
	local cf, ext = model:GetBoundingBox()
	model.WorldPivot = CFrame.new(cf.Position - Vector3.new(0, ext.Y / 2, 0))
end

function AreaKitSetup.Run(root, opts)
	opts = opts or {}
	local dest = opts.Destination
	if not dest and not opts.Keep then
		dest = ReplicatedStorage:FindFirstChild("AreaKit")
		if not dest then
			dest = Instance.new("Folder")
			dest.Name = "AreaKit"
			dest.Parent = ReplicatedStorage
		end
	end

	-- gather each asset's parts, wherever the importer put them
	local groups = {}
	local order = {}
	for _, d in ipairs(root:GetDescendants()) do
		if d:IsA("BasePart") then
			local asset, style = parse(d.Name)
			if asset and AreaKitSetup.Assets[asset] then
				if not groups[asset] then
					groups[asset] = {}
					table.insert(order, asset)
				end
				table.insert(groups[asset], { Part = d, Style = style })
			end
		end
	end

	local done = 0
	for _, asset in ipairs(order) do
		local info = AreaKitSetup.Assets[asset]
		local parts = groups[asset]
		-- reuse the importer's model for this asset when there is one, else make it
		local model = nil
		local p = parts[1].Part.Parent
		while p and p ~= root.Parent do
			if p:IsA("Model") and p.Name == asset then
				model = p
				break
			end
			p = p.Parent
		end
		if not model then
			model = Instance.new("Model")
			model.Name = asset
			model.Parent = parts[1].Part.Parent
		end
		for _, e in ipairs(parts) do
			if not e.Part:IsDescendantOf(model) then
				e.Part.Parent = model
			end
			paint(e.Part, e.Style, opts)
		end
		fit(model, info)
		model:SetAttribute("AreaKitAsset", asset)
		model:SetAttribute("Area", info.Area)
		if dest then
			local old = folderFor(dest, info.Area):FindFirstChild(asset)
			if old and old ~= model then
				old:Destroy()
			end
			model.Parent = folderFor(dest, info.Area)
		end
		done += 1
	end
	print(string.format("AreaKitSetup: %d asset(s) set up%s", done, dest and (" -> " .. dest:GetFullName()) or ""))
	-- leftover empty import containers
	if dest and root ~= workspace and root:IsA("Model") and #root:GetDescendants() == 0 then
		root:Destroy()
	end
	return done
end

-- Re-tint the Accent / Party parts of a placed copy.
function AreaKitSetup.Tint(model, accent, party)
	for _, d in ipairs(model:GetDescendants()) do
		if d:IsA("BasePart") then
			local _, style = parse(d.Name)
			if style == "Accent" and accent then
				d.Color = accent
			elseif style == "Party" and party then
				d.Color = party
			end
		end
	end
end

return AreaKitSetup
